-- Scenario tests for the wand bar. Each test builds a fresh world, loads the
-- addon from the .toc and drives it with the events the Forever client sends.
local H, ROOT = ...

-- Default world: a 1.6s wand, no latency, so the stand-still stretch is the
-- last 0.5s and the reload ends 1.1s after each shot.
local SPEED, STILL = 1.6, 0.5
local SHADOW_BOLT, SEARING_PAIN, CORRUPTION, DRAIN_LIFE = 686, 5676, 172, 689

local tests = {}
local function test(name, fn)
	tests[#tests + 1] = { name = name, fn = fn }
end

local function Setup(options)
	local W = H.NewWorld(options)
	H.LoadAddon(W, ROOT)
	local wand = W.ns.modules.Wand
	return W, wand, wand.bar, wand.state
end

local function Label(bar)
	return bar.label.text
end

test("loads for a warlock and stays hidden until Shoot starts", function()
	local W, wand, bar = Setup()
	H.True(wand.enabled, "module enabled")
	H.True(wand.hasSwingEvent, "PLAYER_SWING registered")
	H.False(bar:IsVisible(), "bar visible")
	H.Equal(W.env.LockeyeDB.modules.Wand.width, 220, "default width")
	H.Equal(#W.printed, 0, "chat lines printed at login")
end)

test("stays off for other classes", function()
	local W = H.NewWorld({ class = "MAGE" })
	H.LoadAddon(W, ROOT)
	H.False(W.ns.modules.Wand.enabled, "wand bar enabled")
	H.False(W.ns.modules.Dots.enabled, "DoT tracker enabled")
	W.Slash("test")
	H.True(W.Printed("only runs on warlocks"), "says why")
end)

test("turning Shoot on shows only the stand-still stretch for the first shot", function()
	local W, wand, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	H.True(bar:IsVisible(), "bar visible")
	H.True(S.synthetic, "first-shot cycle")
	H.Equal(Label(bar), "Stand still", "label")
	H.Near(bar.status.value, (SPEED - STILL) / SPEED, 0.001, "fill starts at the stand-still stretch")
	H.Near(bar.stillZone.width, 220 * STILL / SPEED, 1e-6, "stand-still shading")
end)

test("a shot starts a reload that turns into the stand-still stretch", function()
	local W, wand, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	H.False(S.synthetic, "real cycle")
	H.Equal(Label(bar), "Wand", "label after the shot")
	H.Equal(bar.time.text, "1.6", "time left")
	W.Advance(1.0)
	H.Equal(Label(bar), "Wand", "still reloading")
	H.SameColor(bar.status.barColor, wand.db.colors.reload, "reload color")
	W.Advance(0.2)
	H.Equal(Label(bar), "Stand still", "label in the stretch")
	H.SameColor(bar.status.barColor, wand.db.colors.still, "stand-still color")
	H.Near(bar.status.value, 1.2 / SPEED, 0.02, "fill")
end)

test("moving when the shot is due turns the bar red and the shot waits", function()
	local W, wand, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(1.3)
	W.moving = true
	W.Advance(0.02)
	H.Equal(Label(bar), "Moving", "label")
	H.SameColor(bar.status.barColor, wand.db.colors.blocked, "blocked color")
	W.Advance(0.4) -- the cycle ran out, the client tries and fails
	W.Fire("UNIT_SPELLCAST_FAILED_QUIET", "player", "Cast-x", 5019)
	H.True(S.due, "shot held back")
	H.Equal(bar.status.value, 1, "bar stays full")
	H.Equal(bar.time.text, "0.5", "time to the retry")
	W.moving = false
	W.Advance(0.02)
	H.Equal(Label(bar), "Stand still", "free again")
	W.WandShot()
	H.Equal(Label(bar), "Wand", "the shot went off")
end)

test("moving while reloading doesn't matter", function()
	local W, wand, bar = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.moving = true
	W.Advance(0.5)
	H.Equal(Label(bar), "Wand", "label")
	W.Fire("UNIT_SPELLCAST_FAILED_QUIET", "player", "Cast-x", 5019)
	H.False(wand.state.due, "a failure while reloading isn't the shot")
end)

test("casting into the stand-still stretch shows the cast's end and what it costs", function()
	local W, wand, bar = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.3)
	W.StartCast(SEARING_PAIN, 1.5) -- ends 1.8s after the shot, 0.7s into the stretch
	W.Advance(0.02)
	H.True(bar.castLine:IsShown(), "cast end line")
	H.SameColor(bar.castLine.color, wand.db.colors.clip, "it runs into the stretch")
	H.True(bar.clipZone:IsShown(), "overlap shaded")
	H.Equal(bar.clipText.text, "+0.7", "delay")
	W.Advance(1.0)
	H.Equal(Label(bar), "Casting", "label")
	H.SameColor(bar.status.barColor, wand.db.colors.blocked, "blocked color")
	W.Advance(0.2)
	W.FinishCast()
	W.Advance(0.02)
	H.False(bar.castLine:IsShown(), "line gone after the cast")
	H.Equal(Label(bar), "Stand still", "free to fire")
end)

test("a wand shot proves any cast is over, even if its end event was missed", function()
	local W, wand, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.StartCast(SEARING_PAIN, 1.5)
	W.casting = nil -- the cast ended without UNIT_SPELLCAST_STOP reaching the addon
	W.Advance(1.6)
	W.WandShot()
	H.Equal(S.castGUID, nil, "cast cleared")
	W.Advance(1.2)
	H.Equal(Label(bar), "Stand still", "not stuck on Casting")
end)

test("a cast that ends before the stretch is fine", function()
	local W, wand, bar = Setup({ wandSpeed = 2.6 })
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.StartCast(SEARING_PAIN, 1.5) -- ends at 1.5, the stretch starts at 2.1
	W.Advance(0.02)
	H.True(bar.castLine:IsShown(), "cast end line")
	H.SameColor(bar.castLine.color, wand.db.colors.safe, "safe color")
	H.False(bar.clipZone:IsShown(), "no overlap")
	H.False(bar.clipText:IsShown(), "no delay")
end)

test("the last cast with a cast time sets where a cast still fits", function()
	local W, wand, bar = Setup({ wandSpeed = 2.6 })
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.1)
	H.False(bar.safeLine:IsShown(), "nothing to fit yet")
	W.StartCast(SEARING_PAIN, 1.5)
	W.Advance(1.5)
	W.FinishCast()
	W.WandShot()
	W.Advance(0.6) -- past the next weave check
	-- Reload is 2.1s; a 1.5s cast must start by 0.6s after the shot.
	H.True(bar.safeLine:IsShown(), "safe line")
	H.Near(bar.safeLine.points[1][4], 220 * 0.6 / 2.6, 0.5, "safe line position")
	H.True(bar.safeZone:IsShown(), "safe stretch")
	H.False(bar.clipText:IsShown(), "it fits")
end)

test("a cast that isn't an attack doesn't set where a cast fits", function()
	local W, wand, bar = Setup({ wandSpeed = 2.6 })
	W.StartCast(6201, 3) -- Create Healthstone
	W.Advance(3)
	W.FinishCast()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.6)
	H.False(bar.safeLine:IsShown(), "no line")
end)

test("a tradeskill cast doesn't set where a cast fits", function()
	local W, wand, bar = Setup({ wandSpeed = 2.6 })
	W.StartCast(3914, 1.5, false, true) -- Bolt of Woolen Cloth
	W.Advance(1.5)
	W.FinishCast()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.6)
	H.False(bar.safeLine:IsShown(), "no line")
end)

test("a cast that can't fit moves the line to the start with its cost", function()
	local W, wand, bar = Setup()
	wand.db.weaveSpell = "SHADOW_BOLT" -- 3.0s; the reload is 1.1s
	wand:ApplyLayout()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.6)
	H.True(bar.safeLine:IsShown(), "line shown")
	H.SameColor(bar.safeLine.color, wand.db.colors.clip, "can't fit")
	H.Near(bar.safeLine.points[1][4], 1, 0.01, "at the start")
	H.Equal(bar.clipText.text, "+1.9", "least it costs")
end)

test("Shoot turning off lets the reload run out, then says so in a fight", function()
	local W, wand, bar = Setup()
	local enemy = W.Enemy("Kobold Miner")
	W.Target(enemy)
	W.EnterCombat()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.4)
	W.Fire("STOP_AUTOREPEAT_SPELL")
	W.Advance(0.02)
	H.True(bar:IsVisible(), "still reloading")
	H.Equal(Label(bar), "Wand", "label")
	W.Advance(1.4)
	H.True(bar:IsVisible(), "shown")
	H.Equal(Label(bar), "Shoot is off", "warning")
	H.SameColor(bar.label.textColor, wand.db.colors.warning, "warning color")
	W.Fire("START_AUTOREPEAT_SPELL")
	W.Advance(0.02)
	H.Equal(Label(bar), "Stand still", "back on")
	W.Fire("STOP_AUTOREPEAT_SPELL")
	W.LeaveCombat()
	W.Advance(0.02)
	H.False(bar:IsVisible(), "hidden after the fight")
end)

test("no Shoot-is-off warning in a fight you didn't wand in", function()
	local W, wand, bar = Setup()
	W.Target(W.Enemy("Kobold Miner"))
	W.EnterCombat()
	W.Advance(0.5)
	H.False(bar:IsVisible(), "hidden")
end)

test("secret stats in combat don't matter: PLAYER_SWING carries the speed", function()
	local W, wand, bar, S = Setup()
	W.EnterCombat()
	W.statsSecret = true
	W.Fire("UNIT_ATTACK_SPEED", "player")
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot(1.4) -- a haste effect
	H.Equal(S.speed, 1.4, "speed from the shot")
	W.Advance(0.95)
	H.Equal(Label(bar), "Stand still", "the stretch follows the new speed")
end)

test("without PLAYER_SWING, Shoot's cast event anchors the cycle", function()
	local W, wand, bar, S = Setup({ unknownEvents = { PLAYER_SWING = true } })
	H.False(wand.hasSwingEvent, "no swing event")
	W.Fire("START_AUTOREPEAT_SPELL")
	W.Fire("UNIT_SPELLCAST_SUCCEEDED", "player", "Cast-1", 5019)
	H.False(S.synthetic, "real cycle")
	H.Equal(S.duration, SPEED, "speed from UnitAttackSpeed")
	H.Equal(Label(bar), "Wand", "reloading")
end)

test("Shoot's cast event is ignored when PLAYER_SWING reports the shot", function()
	local W, wand, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot(1.5)
	local start = S.start
	W.Advance(0.3)
	H.Equal(S.start, start, "cycle kept")
	H.Equal(S.duration, 1.5, "PLAYER_SWING's speed kept")
end)

test("facing the wrong way shows on the label", function()
	local W, wand, bar = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(1.2)
	W.Fire("UI_ERROR_MESSAGE", 1, "You are facing the wrong way!")
	W.Advance(0.02)
	H.Equal(Label(bar), "Face your target", "label")
	H.SameColor(bar.label.textColor, wand.db.colors.warning, "warning color")
	W.WandShot()
	H.Equal(Label(bar), "Wand", "cleared by the next shot")
end)

test("out of range dims the fill", function()
	local W, wand, bar = Setup()
	W.Target(W.Enemy("Kobold Miner"))
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.inRange = false
	W.Advance(0.3)
	H.Equal(Label(bar), "Out of range", "label")
	H.Equal(bar.status.barColor[4], wand.db.outOfRangeAlpha, "dimmed")
end)

test("channeling holds the shot like a cast", function()
	local W, wand, bar = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.2)
	W.StartCast(DRAIN_LIFE, 5, true)
	W.Advance(1.0)
	H.Equal(Label(bar), "Casting", "label")
	W.FinishCast()
	W.Advance(0.02)
	H.Equal(Label(bar), "Stand still", "free again")
end)

test("test mode loops a fake wand without real shots", function()
	local W, wand, bar, S = Setup()
	W.Slash("test")
	H.True(bar:IsVisible(), "bar visible")
	H.True(S.fake, "fake cycle")
	W.Advance(2.0)
	H.True(S.fake, "still looping")
	W.Slash("test")
	H.False(bar:IsVisible(), "hidden again")
	H.Equal(S.start, nil, "fake cycle cleared")
end)

test("a loading screen or dying clears the bar", function()
	local W, wand, bar, S = Setup()
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.StartCast(SHADOW_BOLT, 3)
	W.Fire("PLAYER_DEAD")
	H.False(S.shooting, "shooting")
	H.Equal(S.start, nil, "cycle")
	H.Equal(S.castGUID, nil, "cast")
	W.Advance(0.02)
	H.False(bar:IsVisible(), "hidden")
end)

test("an instant DoT between shots doesn't stop the bar", function()
	local W, wand, bar = Setup()
	local enemy = W.Enemy("Kobold Miner")
	W.Target(enemy)
	W.Fire("START_AUTOREPEAT_SPELL")
	W.WandShot()
	W.Advance(0.3)
	W.Cast(CORRUPTION, enemy, 18)
	W.Advance(0.02)
	H.Equal(Label(bar), "Wand", "still reloading")
end)

return tests
